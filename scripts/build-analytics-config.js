/* ============================================
   Generates js/analytics-config.js
   ============================================
   The GA4 Measurement ID is never committed. It is read
   from the GA_MEASUREMENT_ID environment variable at build
   time and written into js/analytics-config.js, which
   js/analytics.js then reads at runtime.

   GA is only switched on for production builds. Vercel sets
   VERCEL_ENV to "production", "preview" or "development" per
   deployment, so preview deploys and local builds produce a
   disabled config and never send data.
   ============================================ */

import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = join(__dirname, '../js/analytics-config.js');

const rawId = (process.env.GA_MEASUREMENT_ID || '').trim();
const vercelEnv = process.env.VERCEL_ENV || '(unset)';
const isProduction = process.env.VERCEL_ENV === 'production';

// Guard against a mistyped ID silently producing a dead tag.
const looksValid = /^G-[A-Z0-9]+$/i.test(rawId);
if (rawId && !looksValid) {
  console.warn(
    `⚠ GA_MEASUREMENT_ID "${rawId}" does not look like a GA4 ID (expected G-XXXXXXXXXX). Analytics left disabled.`
  );
}

const gaId = looksValid ? rawId : null;
const enabled = isProduction && !!gaId;

const banner = '/* Generated by scripts/build-analytics-config.js — do not edit by hand. */';
const body = `window.__RR_ANALYTICS__ = { gaId: ${
  gaId ? JSON.stringify(gaId) : 'null'
}, enabled: ${enabled} };`;

writeFileSync(outFile, `${banner}\n${body}\n`, 'utf8');

if (enabled) {
  console.log(`✓ Analytics config written — GA4 ENABLED (${gaId}, VERCEL_ENV=${vercelEnv})`);
} else {
  const why = !rawId
    ? 'GA_MEASUREMENT_ID not set'
    : !gaId
      ? 'GA_MEASUREMENT_ID is not a valid GA4 ID'
      : `VERCEL_ENV=${vercelEnv} is not "production"`;
  console.log(`✓ Analytics config written — GA4 disabled (${why})`);
}
